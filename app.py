"""
app.py
======
Flask web server for the Intelligent Search Visualizer.

Endpoints
---------
    GET  /            -> the Leaflet map UI (templates/index.html)
    GET  /api/map     -> contents of map_data.json (locations + graph)
    POST /api/search  -> run one search algorithm
                         body: {"start": "...", "goal": "...", "algorithm": "bfs"}
                         resp: {"path": [...], "cost": miles, "nodes_expanded": k,
                                "expanded_order": [...], "time_ms": t, ...}

Run locally:   python app.py        (http://127.0.0.1:5000)
Production:    gunicorn app:app     (see Procfile)
"""

import json
import os
import time

from flask import Flask, jsonify, render_template, request

from informed import INFORMED_ALGORITHMS
from uninformed import UNINFORMED_ALGORITHMS

app = Flask(__name__)

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MAP_DATA_FILE = os.path.join(BASE_DIR, "map_data.json")

# Human-readable names shown in API responses
ALGORITHM_NAMES = {
    "bfs": "Breadth-First Search",
    "dfs": "Depth-First Search",
    "ucs": "Uniform-Cost Search",
    "ids": "Iterative Deepening Search",
    "greedy": "Greedy Best-First Search",
    "astar": "A* Search",
}


def load_map_data():
    """Load graph and location data from map_data.json (generated by data_fetcher.py)."""
    if os.path.exists(MAP_DATA_FILE):
        try:
            with open(MAP_DATA_FILE, "r") as f:
                return json.load(f)
        except Exception as e:  # corrupt file - fall through to empty map
            print(f"Error loading {MAP_DATA_FILE}: {e}")
    return {
        "region": "No map data - run data_fetcher.py",
        "total_cities": 0,
        "total_edges": 0,
        "locations": {},
        "graph": {},
    }


def run_search(algorithm, graph, locations, start, goal):
    """Dispatch to the right search function. Informed searches also need coordinates."""
    if algorithm in UNINFORMED_ALGORITHMS:
        return UNINFORMED_ALGORITHMS[algorithm](graph, start, goal)
    if algorithm in INFORMED_ALGORITHMS:
        return INFORMED_ALGORITHMS[algorithm](graph, start, goal, locations)
    raise ValueError(f"Unknown algorithm '{algorithm}'")


@app.route("/")
def index():
    return render_template("index.html")


@app.route("/api/map", methods=["GET"])
def get_map():
    return jsonify(load_map_data())


@app.route("/api/algorithms", methods=["GET"])
def get_algorithms():
    return jsonify(ALGORITHM_NAMES)


@app.route("/api/search", methods=["POST"])
def search():
    payload = request.get_json(silent=True) or {}
    start = payload.get("start", "")
    goal = payload.get("goal", "")
    algorithm = payload.get("algorithm", "").lower()

    data = load_map_data()
    graph = data.get("graph", {})
    locations = data.get("locations", {})

    # ---- validation -------------------------------------------------------
    if algorithm not in ALGORITHM_NAMES:
        return jsonify({"error": f"Unknown algorithm '{algorithm}'.",
                        "valid_algorithms": list(ALGORITHM_NAMES)}), 400
    if start not in graph or goal not in graph:
        return jsonify({"error": "Start and goal must both be cities in the map."}), 400

    # ---- run the search and time it ---------------------------------------
    t0 = time.perf_counter()
    result = run_search(algorithm, graph, locations, start, goal)
    elapsed_ms = round((time.perf_counter() - t0) * 1000, 3)

    return jsonify({
        "algorithm": algorithm,
        "algorithm_name": ALGORITHM_NAMES[algorithm],
        "start": start,
        "goal": goal,
        "path": result["path"],
        "path_length": max(len(result["path"]) - 1, 0),   # number of road segments
        "cost": result["cost"],
        "nodes_expanded": result["nodes_expanded"],
        "expanded_order": result["expanded_order"],
        "time_ms": elapsed_ms,
        "message": "Path found." if result["path"] else "No path found.",
    })


if __name__ == "__main__":
    port = int(os.environ.get("PORT", 5000))
    app.run(host="0.0.0.0", port=port, debug=True)
